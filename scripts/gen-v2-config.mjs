#!/usr/bin/env node
/**
 * Project the team's roles AND slash commands into OpenCode v2 config files.
 *
 * A v2 plugin cannot create an agent — `AgentEditor` exposes only
 * list/get/default/update/remove (docs/v2/build/plugins, Agent reference) — and
 * `ctx.command.transform.add` was measured NOT to reach the UI on 2.0.16, so
 * both have to live where the built-in Build and Plan agents do:
 *
 *   ~/.config/opencode/agents/<name>.md      frontmatter + body = system prompt
 *   ~/.config/opencode/commands/<name>.md    frontmatter + body = prompt template
 *
 * Everything here is a projection of `src/agents.ts` / `src/commands.ts`
 * through the built `dist/`, including the prompt strings, so the markdown
 * cannot drift from what the v1 personality injects.
 *
 * ONE THING THIS CANNOT VERIFY: the v1 commands carry `agent: architect` (etc.)
 * and that works on v1.  v2 documents `mode: subagent` as "runs ONLY in a child
 * session through the subagent tool", so a command selecting a subagent-only
 * role may not run as that role.  If the live host says so, the fix is one value
 * in src/agents.ts — `mode: "all"` runs either way, and T3 ("only the lead
 * dispatches") is held by the specialists' `subagent: deny` rule rather than by
 * `mode`, so switching costs the picker five extra entries and nothing else.
 *
 * Usage:
 *   node scripts/gen-v2-config.mjs [--dir <path>] [--print] [--force]
 *
 * `--dir` is the base; `agents/` and `commands/` are created under it.
 * Refuses to touch a file it did not generate unless --force is given.
 */

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs"
import { join } from "node:path"
import { homedir } from "node:os"

const MARKER = "generated by @te-river/opencode-team-mode"

const argv = process.argv.slice(2)
const flag = (name) => argv.includes(`--${name}`)
const opt = (name) => {
  const i = argv.indexOf(`--${name}`)
  return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith("--") ? argv[i + 1] : undefined
}

const baseDir = opt("dir") ?? join(homedir(), ".config", "opencode")
const printOnly = flag("print")
const force = flag("force")

const { agents } = await import(new URL("../dist/agents.js", import.meta.url).href)
const { commands } = await import(new URL("../dist/commands.js", import.meta.url).href)
const { triplesFromAgentPermission, V1_ONLY_TOOLS } = await import(
  new URL("../dist/host/v2-permissions.js", import.meta.url).href
)

/** YAML is a superset of JSON, so a JSON scalar is a valid YAML scalar —
 *  and the descriptions are full of em-dashes and colons that a hand-rolled
 *  quote would get wrong. */
const scalar = (v) => JSON.stringify(String(v))

function agentFrontmatter(cfg, triples) {
  const lines = [`---`, `# ${MARKER} — edit src/agents.ts and re-run the generator instead.`]
  if (cfg.description) lines.push(`description: ${scalar(cfg.description)}`)
  lines.push(`mode: ${scalar(cfg.mode ?? "subagent")}`)
  if (cfg.color) lines.push(`color: ${scalar(cfg.color)}`)
  if (triples.length) {
    lines.push("permissions:")
    for (const t of triples) {
      lines.push(`  - action: ${scalar(t.action)}`)
      lines.push(`    resource: ${scalar(t.resource)}`)
      lines.push(`    effect: ${scalar(t.effect)}`)
    }
  }
  lines.push("---", "")
  return lines.join("\n")
}

/** v2's command markdown takes `description` / `agent` / `model` / `subagent` in
 *  frontmatter and the template as the body — deliberately NO `template` key,
 *  which the docs forbid because the body supplies it. */
function commandFrontmatter(cfg) {
  const lines = [`---`, `# ${MARKER} — edit src/commands.ts and re-run the generator instead.`]
  if (cfg.description) lines.push(`description: ${scalar(cfg.description)}`)
  if (cfg.agent) lines.push(`agent: ${scalar(cfg.agent)}`)
  lines.push("---", "")
  return lines.join("\n")
}

const body = (prompt) => {
  const text = String(prompt ?? "").trimEnd()
  // A body that opens with `---` would read as a second frontmatter block.
  return text.startsWith("---") ? text.replace(/^---/, "\\---") : text
}

/**
 * The personality fork, in one place.
 *
 * v2 does not register `tm_ptc_run` — the host's own `execute` (Code Mode)
 * already runs "one program, N tool calls, zero round-trips, only the aggregate
 * entering the context", and a live session proved the governed tm_* results
 * still come back offloaded through it.  v1 has no Code Mode, so it keeps the
 * tool and keeps these sentences untouched.
 *
 * A prompt that names a tool the model cannot call is not a style problem — it
 * costs the round the mandate exists to save — so the v2 markdown says what v2
 * can actually do.  Every key below MUST be found in the shared source or the
 * generator fails: a silent no-op here would ship the v1 sentence to a v2 model
 * and look like success.  `test-v2-adapter` group 8 pins both halves.
 */
const V2_TEXT = [
  ["tm_ptc_run program, keeping only the handle.", "`execute` (the host's Code Mode tool) program, keeping only the handle."],
  ["Batch the recon in one tm_ptc_run program", "Batch the recon in one `execute` program"],
  ["batch recon via tm_ptc_run,", "batch recon via `execute`,"],
  ["is ONE tm_ptc_run, not a chain.", "is ONE `execute` (Code Mode) call, not a chain."],
  ["multi-file batch recon → tm_ptc_run (one program,", "multi-file batch recon → `execute` (one program,"],
  ["your FIRST move is ONE tm_ptc_run program:", "your FIRST move is ONE `execute` (Code Mode) program:"],
  ["## Recon batching (PTC-first)", "## Recon batching (Code Mode first)"],
  ["Local-repo recon is PTC-first:", "Local-repo recon is Code-Mode-first:"],
  ["cross-referencing searches → ONE tm_ptc_run program", "cross-referencing searches → ONE `execute` program"],
  ["tm.read / tm.grep / tm.bash ride inside", "tools.tm_read / tools.tm_grep / tools.tm_bash are reachable inside it"],
  /*
   * The delegation half of the lead prompt.  On v2 the host's tool is named
   * `subagent` — measured, not inferred: a live dispatch reached
   * `execute.before {tool:"subagent"}` and `permission.evaluate {action:"subagent"}`.
   * A mandate that names `task` points at a tool the role cannot call, which costs
   * the round it exists to save (the tm_ptc_run lesson, same shape).  And on v2
   * `background` needs no operator flag — the plugin sets it on every dispatch —
   * so the "pick the shape by rule" instruction is not a choice the model has.
   */
  ["## Delegation — the host's task tool, and what you do while it runs", "## Delegation — the host's subagent tool, and what you do while it runs"],
  ["delegation goes through the host's `task` — governed, visible, killable.", "delegation goes through the host's `subagent` — governed, visible, killable."],
  ["you will keep following up while they run → `task { background: true }`: the", "you will keep following up while they run → `subagent { background: true }`: the"],
  ["`task`. Do not choose background when you would only park waiting for it.",
   "`subagent`. On this host the plugin forces `background: true` on EVERY dispatch, so this is not a choice you make, and the operator flag v1 needed does not exist here."],
  ["Background needs the operator flag `OPENCODE_EXPERIMENTAL_BACKGROUND_SUBAGENTS=true`;",
   "Assume the card is asynchronous: say who is running instead of pretending to block."],
  ["without it `task` only blocks, so say so rather than pretending to overlap.",
   "There is no flag to check and no synchronous fallback to fall back on."],
  ["a background `task` names its own session id", "a background `subagent` names its own session id"],
  ["a synchronous `task` call, so chaining waits", "a synchronous `subagent` call, so chaining waits"],
  ["blocking on `task`", "blocking on `subagent`"],
]

function forkBody(text, hits) {
  let out = text
  for (const [from, to] of V2_TEXT) {
    if (!out.includes(from)) continue
    out = out.split(from).join(to)
    hits.add(from)
  }
  return out
}

/** Every key must land in at least one role, or the fork is silently stale. */
function assertForkApplied(hits) {
  const dead = V2_TEXT.map(([from]) => from).filter((from) => !hits.has(from))
  if (dead.length) {
    throw new Error(
      `v2 提示词分叉有 ${dead.length} 条没命中任何角色（源文改了，这里没跟上）：\n  - ` +
        dead.join("\n  - "),
    )
  }
}

const written = []
const skipped = []

function emit(dir, name, content) {
  const file = join(dir, `${name}.md`)
  if (existsSync(file)) {
    const current = readFileSync(file, "utf8")
    if (!current.includes(MARKER) && !force) {
      skipped.push(`${file} — 不是我生成的文件，未覆盖（--force 强制）`)
      return
    }
    if (current === content) {
      skipped.push(`${file} — 已是最新`)
      return
    }
  }
  if (printOnly) {
    console.log(`=== ${file}\n${content.slice(0, 700)}\n… (${content.length} 字节)`)
    written.push(file)
    return
  }
  mkdirSync(dir, { recursive: true })
  writeFileSync(file, content, "utf8")
  written.push(file)
}

const agentsDir = join(baseDir, "agents")
const forkHits = new Set()
for (const [id, cfg] of Object.entries(agents)) {
  const { triples } = triplesFromAgentPermission(cfg.permission, { escalateShellAsk: false })
  // An `allow` for a tool v2 never registers would claim a capability that does
  // not exist; V1_ONLY_TOOLS is the same set v2.ts skips when registering.
  const v2Triples = triples.filter((t) => !V1_ONLY_TOOLS.has(t.action))
  const text = forkBody(body(cfg.prompt), forkHits)
  emit(agentsDir, id, agentFrontmatter(cfg, v2Triples) + text + "\n")
}
assertForkApplied(forkHits)

const commandsDir = join(baseDir, "commands")
for (const [name, cfg] of Object.entries(commands)) {
  emit(commandsDir, name, commandFrontmatter(cfg) + body(cfg.template) + "\n")
}

console.log(`目标：${agentsDir} 与 ${commandsDir}`)
for (const f of written) console.log(printOnly ? `将写入 ${f}` : `已写入 ${f}`)
for (const s of skipped) console.log(`跳过 ${s}`)
console.log(
  `\n共 ${written.length} 个文件（角色 ${Object.keys(agents).length} + 命令 ${Object.keys(commands).length}）` +
    `${printOnly ? "（--print，未落盘）" : ""}。重启桌面端（或 opencode reload）后 Team 出现在 agent 选择器、/team-* 出现在命令列表。`,
)
