function forkBody(text, hits) {
  let out = text
  for (const [from, to] of V2_TEXT) {
    if (!out.includes(from)) continue
    out = out.split(from).join(to)
    hits.add(from)
  }
  return out
}

/** Every key must land in at least one role, or the fork is silently stale. */
function assertForkApplied(hits) {
  const dead = V2_TEXT.map(([from]) => from).filter((from) => !hits.has(from))
  if (dead.length) {
    throw new Error(
      `v2 提示词分叉有 ${dead.length} 条没命中任何角色（源文改了，这里没跟上）：\n  - ` +
        dead.join("\n  - "),
    )
  }
}

const written = []
const skipped = []

function emit(dir, name, content) {
  const file = join(dir, `${name}.md`)
  if (existsSync(file)) {
    const current = readFileSync(file, "utf8")
    if (!current.includes(MARKER) && !force) {
      skipped.push(`${file} — 不是我生成的文件，未覆盖（--force 强制）`)
      return
    }
    if (current === content) {
      skipped.push(`${file} — 已是最新`)
      return
    }
  }
  if (printOnly) {
    console.log(`=== ${file}\n${content.slice(0, 700)}\n… (${content.length} 字节)`)
    written.push(file)
    return
  }
  mkdirSync(dir, { recursive: true })
  writeFileSync(file, content, "utf8")
  written.push(file)
}

const reclaimed = []
const keptForeign = []
const caseNotes = []
const unverified = []

/** Windows is case-insensitive: `team.md` and `Team.md` are ONE file, and
 *  `realpathSync` echoes the case it was GIVEN rather than the on-disk case, so
 *  a real-path comparison must fold case on win32 — otherwise the reclaim would
 *  delete the very file it just wrote. */
const normPath = (p) => (process.platform === "win32" ? p.toLowerCase() : p)

/**
 * The identity of a file as the OS reports it, or null when `statSync` fails.
 * `dev` + `ino` together name a file on POSIX and on macOS (APFS), where the
 * inode is stable across case spellings of the same name.  Windows is the
 * exception: some Node/FS combinations report `ino: 0` for every file, so a
 * zero inode is treated as "unavailable" rather than as a real identity.
 */
export function statIdentity(p) {
  try {
    const st = statSync(p)
    return { dev: Number(st.dev), ino: Number(st.ino) }
  } catch {
    return null
  }
}

/**
 * Pure file-identity verdict from two stat identities (or null when a stat
 * failed).  Returns:
 *   "same"      — dev+ino both match: the two paths ARE one file
 *   "different" — dev+ino both usable and differ: two distinct files
 *   "fallback"  — inode unavailable (Windows reports 0): the caller may fall
 *                 back to a case-folded real-path comparison
 *   "unknown"   — inode unavailable on a non-Windows platform: we CANNOT tell,
 *                 so the caller must keep the file (fail-safe)
 *
 * The macOS trap this exists for: APFS is case-INSENSITIVE but case-PRESERVING,
 * so `Team.md` and `team.md` are one file while `realpathSync` may echo the
 * spelling it was given.  A real-path comparison would then call them different
 * and delete the file that was just written.  dev+ino is the platform-neutral
 * answer; when it is unavailable we refuse to delete rather than guess (#48).
 */
export function identityVerdict(a, b, platform) {
  const usable = (x) => x != null && Number.isFinite(x.ino) && x.ino !== 0
  if (usable(a) && usable(b)) {
    return a.dev === b.dev && a.ino === b.ino ? "same" : "different"
  }
  return platform === "win32" ? "fallback" : "unknown"
}

/**
 * After a deletion, every file in the keep set must still be on disk.  A
 * vanished target means the reclaim deleted the file it just wrote — the
 * install is broken and must NOT look like success, so the caller prints the
 * error and exits non-zero.  Pure over the `exists` predicate so it is testable
 * without touching the filesystem.
 */
export function verifyKeepIntact(keepPaths, exists = existsSync) {
  const missing = keepPaths.filter((p) => !exists(p))
  return { ok: missing.length === 0, missing }
}

/**
 * The #48 fail-safe's reporting half: a target that vanished during the reclaim
 * means the install is broken, so it must be LOUD and must not exit 0.  Exported
 * so the test can drive the exact sentence and the exit code without having to
 * manufacture a filesystem that defeats the identity guard.
 */
export function reportKeepLoss(missing) {
  console.error(`错误：回收后目标文件消失，安装已中止（#48 fail-safe）：${missing.join(", ")}`)
  process.exitCode = 1
}

/**
 * Reclaim role/command files this generator wrote in a PREVIOUS run but no
 * longer emits — the `team.md` → `Team.md` rename (#47) is the case that
 * motivated it.  On a case-sensitive filesystem (Linux) the old lowercase file
 * survives beside the new one and the host loads TWO Team roles; on a
 * case-insensitive filesystem (Windows, and macOS/APFS by default) the two names
 * are one file, so there is nothing to reclaim and deleting would delete the
 * target.
 *
 * Strict rules:
 *  - only a file carrying MARKER is ours to remove; a hand-written file with a
 *    stale name is left alone and REPORTED, never silently kept.
 *  - "is this the file we just wrote?" is answered by dev+ino first (reliable on
 *    POSIX and macOS), then by a case-folded real path on win32 only.  When
 *    neither can answer, the file is KEPT and reported — a duplicate role is a
 *    far smaller failure than a deleted target (#48).
 *  - after every deletion the keep set is re-checked; a vanished target prints
 *    an error and sets a non-zero exit code.
 *  - deletion goes through rmForceSafe (dist/fs-safe.js): win32 fs.rmSync
 *    silently no-ops on non-ASCII paths, and a reclaim that silently failed
 *    would leave the duplicate role it exists to remove.
 */
function reclaimStale(dir, keepNames, label) {
  if (!existsSync(dir)) return
  const keep = new Set(keepNames.map((n) => `${n}.md`))
  const keepPaths = []
  const keepId = new Map()
  for (const n of keep) {
    const p = join(dir, n)
    if (!existsSync(p)) continue
    keepPaths.push(p)
    keepId.set(n, statIdentity(p))
  }
  for (const entry of readdirSync(dir)) {
    if (!entry.endsWith(".md")) continue
    if (keep.has(entry)) continue
    const file = join(dir, entry)
    const fileId = statIdentity(file)
    // Decide "same file as a target?" per keep entry, most reliable test first.
    let sameAs = null
    let undecidable = false
    for (const n of keep) {
      if (!keepId.has(n)) continue
      const verdict = identityVerdict(fileId, keepId.get(n), process.platform)
      if (verdict === "same") {
        sameAs = n
        break
      }
      if (verdict === "fallback") {
        // win32 with no usable inode: compare case-folded real paths.
        try {
          if (normPath(realpathSync(file)) === normPath(realpathSync(join(dir, n)))) {
            sameAs = n
            break
          }
        } catch {
          undecidable = true
        }
      } else if (verdict === "unknown") {
        undecidable = true
      }
    }
    if (sameAs) {
      // Same file as a target, stored under a DIFFERENT case.  Nothing here is
      // stale and deleting it would delete the file we just wrote — but leaving
      // the old spelling is a real defect, not a cosmetic one: the HOST TAKES AN
      // AGENT'S ID FROM THE FILE NAME.  A machine that still carries the
      // pre-1.7 `team.md` registers the lead as `team`, so the installer's own
      // `default_agent: "Team"` resolves to nothing and the host falls back to
      // `build` — silently, because that fallback is documented as the normal
      // move for a default that names an agent it cannot find.  Measured on
      // 2.0.24 / 2026-10-07 on this very machine: `--agent Team` answered
      // `Agent not found: "Team"`, `--agent team` resolved, and
      // `GET /api/agent` listed `{"id":"team","name":"team"}`.
      //
      // Windows and APFS keep the EXISTING spelling when a write opens that file
      // through the other one, which is how the stale name survives every
      // install, so the rename has to be explicit — and on win32 a case-only
      // rename is itself a no-op, hence the temporary name in the middle.
      if (printOnly) {
        caseNotes.push(`保留 ${file} — 与目标 ${sameAs} 是同一个文件（--print，未修正大小写）`)
        continue
      }
      const target = join(dir, sameAs)
      const tmp = join(dir, `.${entry}.casefix-${process.pid}`)
      try {
        renameSync(file, tmp)
        renameSync(tmp, target)
        caseNotes.push(`已修正大小写 ${entry} → ${sameAs} — 与目标是同一个文件；宿主按文件名取 agent id，不改就一直挂在旧 id 上`)
      } catch (err) {
        // Never leave a half-rename behind: if the second step failed, put the
        // file back under the name we found it (the stale spelling is survivable;
        // a file stranded under the temporary name is not).
        try {
          if (existsSync(tmp) && !existsSync(target)) renameSync(tmp, target)
        } catch {
          /* it stays under the temporary name, and the note below says so */
        }
        caseNotes.push(
          `大小写未修正 ${entry}（目标 ${sameAs}）：${String((err && err.message) || err).replace(/\s+/g, " ").slice(0, 80)}`,
        )
      }
      continue
    }
    if (undecidable) {
      // Neither dev+ino nor a real-path comparison could decide.  Fail safe:
      // keep the file and say so — a duplicate role beats a deleted target.
      unverified.push(`保留 ${file} — 无法确认是否与目标 ${[...keep].join(" / ")} 是同一文件，保留不删`)
      continue
    }
    let current
    try {
      current = readFileSync(file, "utf8")
    } catch {
      continue
    }
    if (!current.includes(MARKER)) {
      keptForeign.push(`保留 ${file} — 不是我生成的（无标记），请自行决定`)
      continue
    }
    if (printOnly) {
      reclaimed.push(`回收 ${file} — 本次不再生成该${label}（--print，未落盘）`)
      continue
    }
    rmForceSafe(file)
    if (existsSync(file)) {
      reclaimed.push(`回收失败 ${file} — 仍在磁盘上，请手动删除`)
    } else {
      reclaimed.push(`回收 ${file} — 本次不再生成该${label}（旧文件已清理）`)
    }
    // #48: a deletion must never take a target with it.  Re-check the keep set
    // after EVERY real deletion; a vanished target is a broken install.
    const intact = verifyKeepIntact(keepPaths)
    if (!intact.ok) {
      reportKeepLoss(intact.missing)
      return
    }
  }
}

function main() {
  const agentsDir = join(baseDir, "agents")
  const forkHits = new Set()
  for (const [id, cfg] of Object.entries(agents)) {
    const { triples } = triplesFromAgentPermission(cfg.permission, { escalateShellAsk: false, agentName: id })
    // An `allow` for a tool v2 never registers would claim a capability that does
    // not exist; V1_ONLY_TOOLS is the same set v2.ts skips when registering.
    const v2Triples = triples.filter((t) => !V1_ONLY_TOOLS.has(t.action))
    const text = forkBody(body(cfg.prompt), forkHits)
    emit(agentsDir, id, agentFrontmatter(cfg, v2Triples) + text + "\n")
  }
  assertForkApplied(forkHits)
  // Reclaim role files a previous run wrote under a name this run no longer emits
  // (the `team.md` → `Team.md` rename, #47).  Runs AFTER the writes so the keep
  // set is the current output, and the identity guard keeps it from deleting a
  // file it just wrote on a case-insensitive filesystem.
  reclaimStale(agentsDir, Object.keys(agents), "角色")

  const commandsDir = join(baseDir, "commands")
  for (const [name, cfg] of Object.entries(commands)) {
    emit(commandsDir, name, commandFrontmatter(cfg) + body(cfg.template) + "\n")
  }
  // Same pass for commands.  No command name has changed yet, so this is a no-op
  // today — it is here so a future rename is closed by the same mechanism rather
  // than by a second, hand-written reclaim that could drift from this one.
  reclaimStale(commandsDir, Object.keys(commands), "命令")

  console.log(`目标：${agentsDir} 与 ${commandsDir}`)
  for (const f of written) console.log(printOnly ? `将写入 ${f}` : `已写入 ${f}`)
  for (const s of skipped) console.log(`跳过 ${s}`)
  for (const r of reclaimed) console.log(r)
  for (const k of keptForeign) console.log(k)
  for (const c of caseNotes) console.log(c)
  for (const u of unverified) console.log(u)
  console.log(
    `\n共 ${written.length} 个文件（角色 ${Object.keys(agents).length} + 命令 ${Object.keys(commands).length}）` +
      `${printOnly ? "（--print，未落盘）" : ""}。重启桌面端（或 opencode reload）后 Team 出现在 agent 选择器、/team-* 出现在命令列表。`,
  )
  if (unverified.length) {
    console.log(`注意：${unverified.length} 个文件无法确认是否与目标同一文件，已保留不删（#48 fail-safe）。`)
  }
}

